"""Deterministic teaching-code emission from validated semantic IR only."""

import hashlib

from easyai.compiler.source_map import CodeWriter
from easyai.compiler.emitters.figures import emit_figures
from easyai.domain.contracts import SourceSpan
from easyai.domain.program import (
    AtomicLayer,
    Conv2dSpec,
    DropoutSpec,
    FlattenSpec,
    LinearSpec,
    NormalizeStep,
    PoolSpec,
    ProgramIR,
    ReluSpec,
    SequentialSpec,
)


def key(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()[:16]


def layer_expression(layer: AtomicLayer) -> str:
    if isinstance(layer, Conv2dSpec):
        return (
            f"nn.Conv2d({layer.in_channels}, {layer.out_channels}, "
            f"{layer.kernel_size}, padding={layer.padding})"
        )
    if isinstance(layer, LinearSpec):
        return f"nn.Linear({layer.in_features}, {layer.out_features})"
    if isinstance(layer, PoolSpec):
        return f"nn.MaxPool2d({layer.kernel_size})"
    if isinstance(layer, DropoutSpec):
        return f"nn.Dropout(p={layer.p!r})"
    if isinstance(layer, ReluSpec):
        return "nn.ReLU()"
    raise TypeError(f"Unsupported layer {type(layer).__name__}")


def emit_program(program: ProgramIR) -> tuple[str, list[SourceSpan]]:
    w = CodeWriter()
    line = w.line
    training = program.training
    origin = training.origin
    line("# Generated by Easy-AI 0.0.0; edit the project, then regenerate.")
    line("import math")
    line("import platform")
    line("import random")
    line("import time")
    import_lines = {
        "torch": "import torch",
        "torch.nn": "from torch import nn",
        "torch.optim": "import torch",
        "torch.utils.data": "import torch",
        "torchvision.datasets": "from torchvision import datasets",
        "torchvision.transforms": "from torchvision import transforms",
        "matplotlib.pyplot": "",
    }
    if any(module not in import_lines for module in program.imports):
        raise ValueError("Untrusted import outside compiler whitelist")
    required = {"torch", "torch.nn", "torchvision.datasets", "torchvision.transforms"}
    emitted_imports: set[str] = set()
    for module in sorted(set(program.imports) | required):
        statement = import_lines[module]
        if statement and statement not in emitted_imports:
            line(statement)
            emitted_imports.add(statement)
    line("import torchvision")
    line("from easyai_runtime import RunContext")
    if training.before or training.body or training.after:
        line("import matplotlib")
        line("matplotlib.use('Agg')")
        line("import matplotlib.pyplot as plt")
        line("from matplotlib.ticker import PercentFormatter")
    line()
    line()
    model_origin = program.model.origin
    line(f"class {program.model.name}(nn.Module):", model_origin)
    line("    def __init__(self):", model_origin, "scaffold")
    line("        super().__init__()", model_origin, "scaffold")
    for index, layer in enumerate(program.model.layers):
        if isinstance(layer, FlattenSpec):
            continue
        if isinstance(layer, SequentialSpec):
            line(f"        self.layer_{index} = nn.Sequential(", layer.origin)
            for child in layer.layers:
                line(f"            {layer_expression(child)},", child.origin)
            line("        )", layer.origin, "scaffold")
        else:
            line(f"        self.layer_{index} = {layer_expression(layer)}", layer.origin)
    line()
    line("    def forward(self, x):", model_origin, "scaffold")
    for index, layer in enumerate(program.model.layers):
        if isinstance(layer, FlattenSpec):
            line("        x = torch.flatten(x, 1)", layer.origin)
        elif isinstance(layer, SequentialSpec):
            # Explicit children expose the same ordered computation and exact child mapping.
            for child_index, child in enumerate(layer.layers):
                line(f"        x = self.layer_{index}[{child_index}](x)", child.origin)
        else:
            line(f"        x = self.layer_{index}(x)", layer.origin)
    line("        return x", model_origin, "scaffold")
    line()
    line()
    line("def main():")
    line(
        f"    context = RunContext.from_cli(default_seed={program.seed}, default_execution_mode={program.execution_mode!r})"
    )
    line("    try:")
    base = "        "

    def run(text: str, semantic: bool = True) -> None:
        line(base + text, origin, "semantic" if semantic else "scaffold")

    run("started = time.monotonic()", False)
    run("random.seed(context.seed)")
    run("torch.manual_seed(context.seed)")
    run("if context.device != 'auto':")
    run("    device = torch.device(context.device)")
    run("    if device.type == 'cuda' and not torch.cuda.is_available():")
    run("        raise RuntimeError('Configured CUDA device is unavailable')")
    run(
        "    if device.type == 'mps' and not (hasattr(torch.backends, 'mps') and torch.backends.mps.is_available()):"
    )
    run("        raise RuntimeError('Configured MPS device is unavailable')")
    run("    selection_reason = 'Device fixed by the verified run configuration'")
    run("elif torch.cuda.is_available():")
    run("    torch.cuda.manual_seed_all(context.seed)")
    run("    device = torch.device('cuda')")
    run("    selection_reason = 'CUDA is available in the selected training environment'")
    run("elif hasattr(torch.backends, 'mps') and torch.backends.mps.is_available():")
    run("    device = torch.device('mps')")
    run("    selection_reason = 'CUDA unavailable; MPS is available'")
    run("else:")
    run("    device = torch.device('cpu')")
    run("    selection_reason = 'CUDA and MPS unavailable; using CPU'")
    run("generator = torch.Generator().manual_seed(context.seed)")
    run("num_workers = context.num_workers")
    run("pin_memory = device.type == 'cuda'")
    run("execution_mode = context.execution_mode")
    run(
        "context.emit('runtime_started', "
        + repr(origin.block_id)
        + ", {'executionMode': execution_mode, 'seed': context.seed})"
    )
    run(
        "context.emit('device_selected', "
        + repr(origin.block_id)
        + ", {'device': str(device), 'selectionReason': selection_reason, 'numWorkers': num_workers, 'pinMemory': pin_memory, 'python': platform.python_version(), 'torch': torch.__version__, 'torchvision': torchvision.__version__, 'platform': platform.platform()})"
    )
    if program.execution_mode == "quick":
        run(
            "print('QUICK CHECK: 1 epoch, at most 1024 training / 256 test samples; not the full example.', flush=True)"
        )
    for transform in program.transforms:
        variable = f"_easyai_transform_{transform.name}_{key(transform.id)}"
        line(base + f"{variable} = transforms.Compose([", transform.origin)
        for step in transform.steps:
            expression = (
                f"transforms.Normalize(mean={step.mean!r}, std={step.std!r})"
                if isinstance(step, NormalizeStep)
                else "transforms.ToTensor()"
            )
            line(base + f"    {expression},", step.origin)
        line(base + "])", transform.origin, "scaffold")
    transform_names = {
        item.id: f"_easyai_transform_{item.name}_{key(item.id)}" for item in program.transforms
    }
    dataset_names = {
        item.id: f"_easyai_dataset_{item.name}_{key(item.id)}" for item in program.datasets
    }
    loader_names = {
        item.id: f"_easyai_loader_{item.name}_{key(item.id)}" for item in program.dataloaders
    }
    for dataset in program.datasets:
        variable = f"_easyai_dataset_{dataset.name}_{key(dataset.id)}"
        line(
            base
            + f"{variable} = datasets.{dataset.dataset_name}(root=str(context.data_root), train={dataset.split == 'train'}, transform={transform_names[dataset.transform_id]}, download=False)",
            dataset.origin,
        )
        if program.execution_mode == "quick":
            limit = 1024 if dataset.split == "train" else 256
            line(
                base
                + f"{variable} = torch.utils.data.Subset({variable}, range(min({limit}, len({variable}))))",
                dataset.origin,
            )
    for loader in program.dataloaders:
        line(
            base
            + f"{loader_names[loader.id]} = torch.utils.data.DataLoader({dataset_names[loader.dataset_id]}, batch_size={loader.batch_size}, shuffle={loader.shuffle}, num_workers=num_workers, pin_memory=pin_memory, generator=generator)",
            loader.origin,
        )
    run(f"train_loader = {loader_names[training.train_loader_id]}")
    run(f"test_loader = {loader_names[training.test_loader_id]}")
    run("if len(train_loader.dataset) == 0 or len(test_loader.dataset) == 0:")
    run("    raise ValueError('Training and test datasets must be nonempty')")
    run(f"model = {program.model.name}().to(device)")
    run("criterion = nn.CrossEntropyLoss()")
    momentum = ", momentum=0.9" if training.optimizer == "SGD" else ""
    run(
        f"optimizer = torch.optim.{training.optimizer}(model.parameters(), lr={training.learning_rate!r}{momentum})"
    )
    run("epoch_history, train_loss_history, test_accuracy_history = [], [], []")
    run("last_progress = time.monotonic()", False)
    emit_figures(w, program, training.before, "before", base)
    epochs = 1 if program.execution_mode == "quick" else training.epochs
    run(f"for epoch in range(1, {epochs} + 1):")
    for text in [
        "    context.check_cancelled()",
        "    model.train()",
        "    total_loss, total_samples = 0.0, 0",
        "    for x, y in train_loader:",
        "        context.check_cancelled()",
        "        x, y = x.to(device), y.to(device)",
        "        logits = model(x)",
        "        loss = criterion(logits, y)",
        "        if not math.isfinite(float(loss.item())):",
        "            raise ValueError('Non-finite training loss')",
        "        optimizer.zero_grad()",
        "        loss.backward()",
        "        optimizer.step()",
        "        total_loss += float(loss.item()) * int(x.size(0))",
        "        total_samples += int(x.size(0))",
        "        if time.monotonic() - last_progress >= 1.0:",
        f"            context.emit('progress', {origin.block_id!r}, {{'epoch': epoch, 'trainSamplesCompleted': total_samples}})",
        "            last_progress = time.monotonic()",
        "    if total_samples == 0:",
        "        raise ValueError('Empty training loader')",
        "    train_loss = total_loss / total_samples",
        "    model.eval()",
        "    correct, test_samples = 0, 0",
        "    with torch.no_grad():",
        "        for x, y in test_loader:",
        "            context.check_cancelled()",
        "            x, y = x.to(device), y.to(device)",
        "            predicted = model(x).argmax(dim=1)",
        "            correct += int((predicted == y).sum().item())",
        "            test_samples += int(y.size(0))",
        "    if test_samples == 0:",
        "        raise ValueError('Empty test loader')",
        "    test_accuracy = correct / test_samples",
        "    epoch_history.append(epoch)",
        "    train_loss_history.append(train_loss)",
        "    test_accuracy_history.append(test_accuracy)",
        "    metrics = {'epoch': epoch, 'train_loss': train_loss, 'test_accuracy': test_accuracy, 'train_samples': total_samples, 'test_samples': test_samples, 'elapsed_seconds': time.monotonic() - started}",
        f"    context.emit('epoch_completed', {origin.block_id!r}, metrics)",
        "    print(f'Epoch {epoch}: loss={train_loss:.6f}, test accuracy={test_accuracy:.2%}', flush=True)",
    ]:
        run(text)
    emit_figures(w, program, training.body, "epoch_end", base + "    ")
    emit_figures(w, program, training.after, "after", base)
    run("context.check_cancelled()")
    run("with context.atomic_target('outputs/model.pth') as model_path:")
    run("    torch.save(model.state_dict(), model_path)")
    run(f"context.artifact('outputs/model.pth', 'model', {origin.block_id!r}, [])")
    run(
        f"context.emit('pipeline_completed', {origin.block_id!r}, {{'epochs': len(epoch_history), 'executionMode': execution_mode}})"
    )
    line("    except Exception as error:")
    line(f"        context.report_failure(error, {origin.block_id!r})")
    line("        raise")
    line("    finally:")
    line("        context.close()")
    line()
    line()
    line("if __name__ == '__main__':")
    line("    main()")
    return w.code(), w.spans
